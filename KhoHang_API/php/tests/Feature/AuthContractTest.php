<?php

namespace Tests\Feature;

use App\Support\Jwt;
use App\Support\Passwords;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\DB;
use Tests\TestCase;

class AuthContractTest extends TestCase
{
    use RefreshDatabase;

    protected function setUp(): void
    {
        parent::setUp();
        $now = '2026-01-01 00:00:00.000000';
        // passlib-style $2b$ hash produced by the FastAPI backend for "admin123"
        DB::table('users')->insert([
            ['id' => 'u1', 'username' => 'admin', 'email' => 'admin@example.com', 'password_hash' => Passwords::hash('admin123'),
                'passkey_hash' => Passwords::hash('246810'), 'role' => 'admin', 'is_verified' => 1, 'created_at' => $now, 'updated_at' => $now],
            ['id' => 'u2', 'username' => 'nopk', 'email' => 'nopk@example.com', 'password_hash' => Passwords::hash('secret1'),
                'passkey_hash' => null, 'role' => 'staff', 'is_verified' => 1, 'created_at' => $now, 'updated_at' => $now],
        ]);
        DB::table('warehouses')->insert(['id' => 1, 'name' => 'K', 'code' => 'K1', 'managers' => '[]', 'is_active' => 1, 'created_at' => $now, 'updated_at' => $now]);
    }

    private function token(string $sub = 'u1'): array
    {
        return ['Authorization' => 'Bearer '.Jwt::encode(['sub' => $sub, 'username' => 'x'])];
    }

    public function test_login_returns_legacy_shape(): void
    {
        $this->postJson('/auth/login', ['username_or_email' => ' ADMIN ', 'password' => 'admin123'])
            ->assertOk()
            ->assertJsonPath('token_type', 'bearer')
            ->assertJsonPath('user.has_passkey', true)
            ->assertJsonStructure(['access_token', 'user' => ['id', 'username', 'email', 'display_name', 'avatar_url', 'role', 'is_verified']]);
        $this->postJson('/auth/login', ['username_or_email' => 'admin', 'password' => 'bad'])
            ->assertStatus(401)->assertExactJson(['detail' => 'Invalid credentials']);
    }

    public function test_passlib_2b_hash_is_accepted(): void
    {
        // Generated by passlib.hash.bcrypt for "admin123" (FastAPI backend).
        $legacy = '$2b$12$EA47fTxicxCFLJ3XXCJAseEPDn/Ri7pmG/3jWPaAjfmDZPGcPp.8e';
        $this->assertTrue(Passwords::verify('admin123', $legacy));
        $this->assertFalse(Passwords::verify('admin124', $legacy));
        $this->assertStringStartsWith('$2b$', Passwords::hash('x'));
    }

    public function test_token_errors_use_fastapi_detail(): void
    {
        $this->getJson('/auth/me')->assertStatus(401)->assertExactJson(['detail' => 'Authentication required']);
        $this->getJson('/auth/me', ['Authorization' => 'Bearer nope'])->assertStatus(401)->assertExactJson(['detail' => 'Invalid or expired token']);
        $expired = Jwt::encode(['sub' => 'u1'], -10);
        $this->getJson('/auth/me', ['Authorization' => "Bearer $expired"])->assertStatus(401);
        $this->getJson('/auth/me', $this->token('ghost'))->assertStatus(401)->assertExactJson(['detail' => 'User not found']);
        $this->getJson('/auth/me', $this->token())->assertOk()->assertJsonPath('username', 'admin');
    }

    public function test_warehouse_update_and_delete_require_real_passkey_header(): void
    {
        $h = $this->token();
        $this->putJson('/warehouses/1', ['name' => 'X'], $h)->assertStatus(400)->assertExactJson(['detail' => 'Thiếu passkey (X-Passkey)']);
        // query passkey is not accepted for warehouses (no secrets in new URLs)
        $this->putJson('/warehouses/1?passkey=246810', ['name' => 'X'], $h)->assertStatus(400);
        $this->putJson('/warehouses/1', ['name' => 'X'], $h + ['X-Passkey' => '123456'])->assertStatus(403)->assertExactJson(['detail' => 'Passkey không hợp lệ']);
        $this->putJson('/warehouses/1', ['name' => 'X'], $this->token('u2') + ['X-Passkey' => '123456'])->assertStatus(403)->assertExactJson(['detail' => 'User chưa thiết lập passkey']);
        $this->putJson('/warehouses/1', ['name' => 'X'], $h + ['X-Passkey' => '246810'])->assertOk()->assertJsonPath('name', 'X');
        $this->deleteJson('/warehouses/1', [], $h + ['X-Passkey' => '000000'])->assertStatus(403);
        $this->assertSame(1, DB::table('warehouses')->count());
        $this->deleteJson('/warehouses/1', [], $h + ['X-Passkey' => '246810'])->assertOk()->assertExactJson(['message' => 'Đã xóa kho']);
        $this->assertSame(0, DB::table('warehouses')->count());
    }

    public function test_login_is_rate_limited(): void
    {
        for ($i = 0; $i < 10; $i++) {
            $this->postJson('/auth/login', ['username_or_email' => 'admin', 'password' => 'bad'])->assertStatus(401);
        }
        $this->postJson('/auth/login', ['username_or_email' => 'admin', 'password' => 'admin123'])
            ->assertStatus(429)->assertHeader('Retry-After');
    }

    public function test_validation_errors_use_fastapi_shape(): void
    {
        $this->postJson('/auth/login', ['username_or_email' => 'a'])
            ->assertStatus(422)
            ->assertJsonPath('detail.0.type', 'missing')
            ->assertJsonPath('detail.0.loc', ['body', 'password'])
            ->assertJsonPath('detail.0.msg', 'Field required');
    }
}
